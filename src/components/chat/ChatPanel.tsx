/**
 * Sanitizes chat input text:
 * - Trims leading and trailing whitespace
 * - Normalizes Unicode zero-width characters and full-width whitespace
 * - Strips dangerous script / iframe injection tags
 * - Returns clean sanitized string or empty string
 */
export function sanitizeChatInput(rawInput: string | null | undefined): string {
  if (typeof rawInput !== "string") return "";

  // Normalize Unicode invisible spaces & zero-width characters
  const normalized = rawInput
    .replace(/[\u200B-\u200D\uFEFF]/g, "") // Zero-width spaces and joiners
    .replace(/[\u00A0\u1680\u2000-\u200A\u202F\u205F\u3000]/g, " ") // Non-breaking / ideographic spaces
    .trim();

  if (!normalized) return "";

  // Strip script and iframe injection tags
  return normalized
    .replace(/<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>/gi, "")
    .replace(/<iframe\b[^<]*(?:(?!<\/iframe>)<[^<]*)*<\/iframe>/gi, "");
}

/**
 * Formats large token counts compactly and readably according to repository requirements:
 * 800 -> 800
 * 1200 -> 1.2k
 * 7800 -> 7.8k
 * 8000 -> 8k
 * 12000 -> 12k
 */
export function formatTokenCount(count: number): string {
  if (isNaN(count) || count <= 0) return "0";
  if (count < 1000) return String(Math.round(count));

  const thousands = count / 1000;
  const rounded = Number(thousands.toFixed(1));
  return Number.isInteger(rounded) ? `${Math.round(rounded)}k` : `${rounded}k`;
}

/**
 * Derives and clamps token usage progress (0% - 100%).
 * Prevents negative values, NaNs, or layout breaking when over capacity.
 */
export function calculateTokenProgress(
  tokens: number,
  capacity: number = DEFAULT_CONTEXT_CAPACITY,
): {
  percentage: number;
  clampedPercentage: number;
  isApproaching: boolean;
  isOverCapacity: boolean;
} {
  const safeCapacity = capacity > 0 ? capacity : DEFAULT_CONTEXT_CAPACITY;
  const safeTokens = Math.max(0, isNaN(tokens) ? 0 : tokens);
  const rawPercentage = (safeTokens / safeCapacity) * 100;
  const percentage = isNaN(rawPercentage) ? 0 : rawPercentage;
  const clampedPercentage = Math.min(100, Math.max(0, percentage));
  const isApproaching = percentage >= 80 && percentage < 100;
  const isOverCapacity = percentage >= 100;

  return {
    percentage,
    clampedPercentage,
    isApproaching,
    isOverCapacity,
  };
}

/**
 * Detects whether the active conversation has experienced context compression.
 * Checks for:
 * 1. Explicit boolean flag (`isCompressed` / `contextCompressed`)
 * 2. System messages generated by `compressContext` containing `[PRIOR CONTEXT & PARAMETERS]`
 * 3. Message metadata indicating compression from API route
 */
export function checkIsContextCompressed(
  messages: Array<ChatMessageLike | Message> = [],
  explicitIsCompressed?: boolean,
): boolean {
  if (explicitIsCompressed) return true;
  if (!Array.isArray(messages) || messages.length === 0) return false;

  return messages.some((raw) => {
    if (!raw) return false;
    const m = raw as any;
    if (m.isCompressed === true || m.contextCompressed === true) return true;
    if (m.role === "system" && typeof m.content === "string") {
      return (
        m.content.startsWith("[PRIOR CONTEXT & PARAMETERS]") ||
        m.content.includes("Prior Context:")
      );
    }
    if (Array.isArray(m.agentSteps)) {
      return m.agentSteps.some(
        (step: any) =>
          step?.agent === "Compression" ||
          step?.compressed === true ||
          (step?.result as Record<string, unknown>)?.compressed === true,
      );
    }
    return false;
  });
}

/**
 * Hook to compute memoized token estimates and progress metrics.
 * Separates historical conversation token estimation from active draft input
 * to maintain 60fps responsive typing performance without repeated retokenization.
 */
export function useChatTokens(
  messages: Array<ChatMessageLike | Message> = [],
  input: string = "",
  contextCapacity: number = DEFAULT_CONTEXT_CAPACITY,
) {
  const historyTokens = useMemo(() => {
    if (!Array.isArray(messages)) return 0;
    return messages.reduce((acc, m) => {
      if (!m) return acc;
      const text = typeof m === "string" ? m : m.content || "";
      return acc + (text ? estimateTokens(text) : 0);
    }, 0);
  }, [messages]);

  const draftTokens = useMemo(() => {
    if (!input || typeof input !== "string") return 0;
    return estimateTokens(input);
  }, [input]);

  const totalTokens = historyTokens + draftTokens;

  const progress = useMemo(
    () => calculateTokenProgress(totalTokens, contextCapacity),
    [totalTokens, contextCapacity],
  );

  return {
    historyTokens,
    draftTokens,
    totalTokens,
    formattedUsage: formatTokenCount(totalTokens),
    formattedCapacity: formatTokenCount(contextCapacity),
    ...progress,
  };
}

