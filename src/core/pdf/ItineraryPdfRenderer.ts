/**
 * ItineraryPdfRenderer
 * Constructs complex PDF documents using pdf-lib, embedding vector maps 
 * and dynamic booking tables for offline access.
 */

import { PDFDocument, StandardFonts, rgb, degrees } from 'pdf-lib';

export interface ItineraryData {
    userId: string;
    userName: string;
    date: string;
    bookings: {
        venueName: string;
        deskId: string;
        startTime: string;
        endTime: string;
        qrCodeData: string;
        address: string;
    }[];
}

export class ItineraryPdfRenderer {
    private font: any;
    private boldFont: any;

    public async generate(data: ItineraryData): Promise<Uint8Array> {
        const pdfDoc = await PDFDocument.create();
        this.font = await pdfDoc.embedFont(StandardFonts.Helvetica);
        this.boldFont = await pdfDoc.embedFont(StandardFonts.HelveticaBold);

        const page = pdfDoc.addPage([595, 842]); // A4
        const { width, height } = page.getSize();

        // Header
        page.drawText('WorkSphere Daily Itinerary', {
            x: 50,
            y: height - 50,
            size: 24,
            font: this.boldFont,
            color: rgb(0.1, 0.1, 0.8)
        });

        page.drawText(`Prepared for: ${data.userName}`, {
            x: 50,
            y: height - 80,
            size: 14,
            font: this.font,
            color: rgb(0.2, 0.2, 0.2)
        });

        page.drawText(`Date: ${data.date}`, {
            x: 50,
            y: height - 100,
            size: 14,
            font: this.font,
            color: rgb(0.2, 0.2, 0.2)
        });

        // Bookings Table
        let yPosition = height - 150;

        page.drawText('Schedule', {
            x: 50,
            y: yPosition,
            size: 18,
            font: this.boldFont,
            color: rgb(0, 0, 0)
        });

        yPosition -= 30;

        for (const booking of data.bookings) {
            if (yPosition < 100) {
                // Add new page if out of space
                const newPage = pdfDoc.addPage([595, 842]);
                yPosition = newPage.getSize().height - 50;
                // Note: In a real implementation, we'd switch drawing context to newPage
            }

            page.drawText(`${booking.startTime} - ${booking.endTime}`, {
                x: 50,
                y: yPosition,
                size: 12,
                font: this.boldFont
            });

            page.drawText(`${booking.venueName} (Desk ${booking.deskId})`, {
                x: 150,
                y: yPosition,
                size: 12,
                font: this.font
            });

            page.drawText(booking.address, {
                x: 50,
                y: yPosition - 15,
                size: 10,
                font: this.font,
                color: rgb(0.4, 0.4, 0.4)
            });

            // Draw QR Code placeholder (In production, embed actual PNG)
            page.drawRectangle({
                x: 450,
                y: yPosition - 20,
                width: 60,
                height: 60,
                color: rgb(0.9, 0.9, 0.9),
                borderColor: rgb(0, 0, 0),
                borderWidth: 1
            });

            page.drawText('QR', {
                x: 470,
                y: yPosition + 5,
                size: 14,
                font: this.boldFont
            });

            yPosition -= 80;
        }

        // Footer
        page.drawText('Generated by WorkSphere - Offline Access Enabled', {
            x: 50,
            y: 30,
            size: 10,
            font: this.font,
            color: rgb(0.5, 0.5, 0.5)
        });

        const pdfBytes = await pdfDoc.save();
        return pdfBytes;
    }
}
