/**
 * AgeVerificationCircuit.ts
 * Defines the Circom logic representation and witness generation 
 * to prove that the user's encrypted birthdate satisfies the venue's minimum age threshold.
 */

export interface CircuitInputs {
    birthdate: bigint; // Unix timestamp of birthdate
    currentTimestamp: bigint; // Current Unix timestamp
    minAgeSeconds: bigint; // Minimum age in seconds (e.g., 18 years * 365.25 * 24 * 60 * 60)
    salt: bigint; // Random salt for zero-knowledge
}

export interface ProofArtifacts {
    proof: Uint8Array;
    publicSignals: string[];
}

export class AgeVerificationCircuit {
    private wasmPath: string;
    private zkeyPath: string;

    constructor(wasmPath: string, zkeyPath: string) {
        this.wasmPath = wasmPath;
        this.zkeyPath = zkeyPath;
    }

    public generateInputs(birthdate: Date, minAgeYears: number): CircuitInputs {
        const birthTimestamp = BigInt(Math.floor(birthdate.getTime() / 1000));
        const currentTimestamp = BigInt(Math.floor(Date.now() / 1000));

        // 1 year = 31,557,600 seconds (accounting for leap years)
        const minAgeSeconds = BigInt(minAgeYears) * BigInt(31557600);

        // Generate a random 128-bit salt
        const saltArray = new Uint8Array(16);
        crypto.getRandomValues(saltArray);
        const salt = BigInt('0x' + Array.from(saltArray).map(b => b.toString(16).padStart(2, '0')).join(''));

        return {
            birthdate: birthTimestamp,
            currentTimestamp,
            minAgeSeconds,
            salt
        };
    }

    public async generateWitness(inputs: CircuitInputs): Promise<Uint8Array> {
        // In a real implementation, this calls the snarkjs.wtns.calculate function
        // using the compiled Circom WASM. Here we simulate the witness generation.

        const ageInSeconds = inputs.currentTimestamp - inputs.birthdate;
        const isOldEnough = ageInSeconds >= inputs.minAgeSeconds;

        if (!isOldEnough) {
            throw new Error('Age verification failed: User does not meet minimum age requirement.');
        }

        // Mock witness buffer (normally generated by Circom WASM)
        const witnessData = [
            BigInt(1), // Constant 1
            inputs.birthdate,
            inputs.currentTimestamp,
            inputs.minAgeSeconds,
            inputs.salt,
            ageInSeconds,
            isOldEnough ? BigInt(1) : BigInt(0)
        ];

        // Serialize to Uint8Array
        const buffer = new Uint8Array(witnessData.length * 32);
        for (let i = 0; i < witnessData.length; i++) {
            const hex = witnessData[i].toString(16).padStart(64, '0');
            for (let j = 0; j < 32; j++) {
                buffer[i * 32 + j] = parseInt(hex.substr(j * 2, 2), 16);
            }
        }

        return buffer;
    }

    public async verifyProof(proof: Uint8Array, publicSignals: string[]): Promise<boolean> {
        // In production, this uses snarkjs.groth16.verify with the verification key
        // For demonstration, we validate the structure
        if (proof.length === 0 || publicSignals.length === 0) return false;

        // Mock verification logic
        console.log('[Circuit] Verifying ZK Proof locally...');
        return true;
    }

    public getCircuitMetadata(): { wasm: string; zkey: string } {
        return {
            wasm: this.wasmPath,
            zkey: this.zkeyPath
        };
    }
}